package Testing_for_bascially_everything.assets;

import javafx.scene.image.Image;

import java.io.File;
import java.net.URL;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

/**
 * Central access point for everything bundled under
 * {@code src/main/resources/Testing_for_bascially_everything/assets}.
 *
 * <p>Poster thumbnails are real PNG files generated by
 * {@code tools/GeneratePosters.java}; the demo falls back to its gradient cards
 * when a file is missing. Clips are the bundled Lord of the Rings scenes, and
 * {@link #clipsDirectory()} exposes their folder for the file chooser when the
 * project is run from source.</p>
 */
public final class AssetCatalog {

    private static final String ROOT = "/Testing_for_bascially_everything/assets/";
    public static final String POSTER_ROOT = ROOT + "posters/";
    public static final String CLIP_ROOT = ROOT + "clips/";

    private static final String[] IMAGE_EXTENSIONS = {"png", "jpg", "jpeg", "webp"};
    private static final Map<String, Image> POSTER_CACHE = new HashMap<>();
    private static final Object POSTER_LOCK = new Object();

    /** Decodes posters off the FX thread so startup is not serialised by PNG loading. */
    private static final ExecutorService POSTER_LOADER = Executors.newFixedThreadPool(
        Math.max(2, Math.min(4, Runtime.getRuntime().availableProcessors())),
        runnable -> {
            Thread thread = new Thread(runnable, "poster-loader");
            thread.setDaemon(true);
            return thread;
        });

    /** A clip that ships with the project. */
    public record Clip(String label, String relativePath) { }

    private static final List<Clip> BUNDLED_CLIPS = List.of(
        new Clip("The Lord of the Rings - Scene 1", "LordOfTheRings/scene1.mp4"),
        new Clip("The Lord of the Rings - Scene 2", "LordOfTheRings/scene2.mp4"),
        new Clip("The Lord of the Rings - Scene 3", "LordOfTheRings/scene3.mp4")
    );

    private AssetCatalog() {
    }

    /** The demo clips bundled with the project. */
    public static List<Clip> bundledClips() {
        return BUNDLED_CLIPS;
    }

    /** Resolves a bundled clip, or {@code null} when it is not on the classpath. */
    public static URL clip(String relativePath) {
        return AssetCatalog.class.getResource(CLIP_ROOT + relativePath);
    }

    /** The poster artwork for a slug, or {@code null} when no image is bundled. */
    public static Image poster(String slug) {
        synchronized (POSTER_LOCK) {
            if (POSTER_CACHE.containsKey(slug)) {
                return POSTER_CACHE.get(slug);
            }
        }
        Image image = null;
        for (String extension : IMAGE_EXTENSIONS) {
            URL url = AssetCatalog.class.getResource(POSTER_ROOT + slug + "." + extension);
            if (url != null) {
                image = new Image(url.toExternalForm(), 540, 810, true, true, false);
                break;
            }
        }
        synchronized (POSTER_LOCK) {
            if (!POSTER_CACHE.containsKey(slug)) {
                POSTER_CACHE.put(slug, image);
            }
            return POSTER_CACHE.get(slug);
        }
    }

    /**
     * Loads every slug in parallel and waits for the pool to finish. Called once
     * during startup so the first rendered frame already has its artwork.
     */
    public static void preloadPosters(Collection<String> slugs) {
        List<CompletableFuture<Void>> jobs = new ArrayList<>();
        for (String slug : new LinkedHashSet<>(slugs)) {
            jobs.add(CompletableFuture.runAsync(() -> poster(slug), POSTER_LOADER));
        }
        CompletableFuture.allOf(jobs.toArray(new CompletableFuture[0])).join();
    }

    /**
     * The clips folder on disk, when the app runs from the project (classes
     * directory or working directory). Returns {@code null} for a packaged jar,
     * where the resources cannot be browsed with a file chooser.
     */
    public static File clipsDirectory() {
        URL url = AssetCatalog.class.getResource(CLIP_ROOT);
        if (url != null && "file".equals(url.getProtocol())) {
            try {
                File dir = new File(url.toURI());
                if (dir.isDirectory()) {
                    return dir;
                }
            } catch (Exception ignored) {
                // fall through to the source tree lookup
            }
        }
        File source = new File("src/main/resources" + CLIP_ROOT);
        return source.isDirectory() ? source : null;
    }
}
